    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        String username = txtUsername.getText().trim();
        String passLama = new String(txtPassLama.getPassword());
        String passBaru = new String(txtPassBaru.getPassword());
        String konfirmPassBaru = new String(txtKonfirmPassBaru.getPassword());

        if (username.isEmpty() || passLama.isEmpty() || passBaru.isEmpty() || konfirmPassBaru.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Semua data wajib diisi!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!passBaru.equals(konfirmPassBaru)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Konfirmasi password baru tidak cocok!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            java.sql.Connection conn = Koneksi.koneksi.getKoneksi();
            
            // Cek password lama
            String sqlCek = "SELECT Password FROM data_admin WHERE Username = ?";
            java.sql.PreparedStatement psCek = conn.prepareStatement(sqlCek);
            psCek.setString(1, username);
            java.sql.ResultSet rs = psCek.executeQuery();
            
            if (rs.next()) {
                String realPass = rs.getString("Password");
                if (!realPass.equals(passLama)) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Password lama salah!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
                    return;
                }
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Username tidak ditemukan!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Update ke password baru
            String sqlUpdate = "UPDATE data_admin SET Password = ? WHERE Username = ?";
            java.sql.PreparedStatement psUpdate = conn.prepareStatement(sqlUpdate);
            psUpdate.setString(1, passBaru);
            psUpdate.setString(2, username);
            psUpdate.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this, "Password berhasil diperbarui!", "Sukses", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            
            // Reset fields
            txtUsername.setText("");
            txtPassLama.setText("");
            txtPassBaru.setText("");
            txtKonfirmPassBaru.setText("");
            
            // Kembali ke dashboard
            btnBatalActionPerformed(evt);

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error Database: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSimpanActionPerformed


